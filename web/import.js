const TYPES = new Set(['image/jpeg', 'image/png', 'image/webp']);
const LIMIT = 10 * 1024 * 1024;

function photoError(code) {
  return Object.assign(new Error(code), { code });
}

function scaleCanvas(source, maxEdge) {
  const width = source.naturalWidth || source.width;
  const height = source.naturalHeight || source.height;
  if (!width || !height) throw photoError('invalidPhoto');
  const ratio = Math.min(1, maxEdge / Math.max(width, height));
  const canvas = document.createElement('canvas');
  canvas.width = Math.max(1, Math.round(width * ratio));
  canvas.height = Math.max(1, Math.round(height * ratio));
  const ctx = canvas.getContext('2d', { alpha: false });
  ctx.fillStyle = '#fff';
  ctx.fillRect(0, 0, canvas.width, canvas.height);
  ctx.drawImage(source, 0, 0, canvas.width, canvas.height);
  return canvas;
}

async function readPhoto(file, maxEdge = 2200) {
  if (!file || file.size > LIMIT) throw photoError(file ? 'largePhoto' : 'invalidPhoto');
  if (!TYPES.has((file.type || '').toLowerCase())) throw photoError('invalidPhoto');
  const bytes = new Uint8Array(await file.slice(0, 12).arrayBuffer());
  const header = String.fromCharCode(...bytes);
  const valid =
    (bytes[0] === 255 && bytes[1] === 216 && bytes[2] === 255) ||
    (bytes[0] === 137 && header.slice(1, 4) === 'PNG') ||
    (header.startsWith('RIFF') && header.slice(8) === 'WEBP');
  if (!valid) throw photoError('invalidPhoto');

  const url = URL.createObjectURL(file);
  try {
    const image = new Image();
    image.src = url;
    await image.decode();
    return scaleCanvas(image, maxEdge);
  } catch {
    throw photoError('invalidPhoto');
  } finally {
    URL.revokeObjectURL(url);
  }
}

function jpeg(canvas, edge, targetBytes) {
  let scaled = scaleCanvas(canvas, edge);
  while (true) {
    for (const quality of [0.85, 0.72, 0.55]) {
      const encoded = scaled.toDataURL('image/jpeg', quality);
      if (encoded.length * 0.75 <= targetBytes) return encoded;
    }
    if (Math.max(scaled.width, scaled.height) < 180) throw photoError('invalidPhoto');
    scaled = scaleCanvas(scaled, Math.max(120, Math.max(scaled.width, scaled.height) * 0.76));
  }
}

/**
 * The model sees each image at a little over a megapixel, so a larger shelf photo also goes in
 * as overlapping zoomed tiles. Positions are whole percentages of the photo.
 */
export function planTiles(width, height, maxTiles = 6) {
  if (maxTiles < 2 || width * height <= 1.5e6) return [];
  const overlap = 0.3;
  const share = n => 1 / (n - (n - 1) * overlap);
  const grids = width >= height ? [[2, 1], [2, 2], [3, 2]] : [[1, 2], [2, 2], [2, 3]];
  let pick = null;
  for (const [cols, rows] of grids) {
    if (cols * rows > maxTiles) break;
    pick = [cols, rows];
    if (width * share(cols) * height * share(rows) <= 2e6) break;
  }
  if (!pick) return [];
  const [cols, rows] = pick;
  const w = cols === 1 ? 100 : Math.round(100 * share(cols)), h = rows === 1 ? 100 : Math.round(100 * share(rows));
  const tiles = [];
  for (let j = 0; j < rows; j++)
    for (let i = 0; i < cols; i++)
      tiles.push({
        x: cols === 1 ? 0 : Math.round((i * (100 - w)) / (cols - 1)),
        y: rows === 1 ? 0 : Math.round((j * (100 - h)) / (rows - 1)),
        w,
        h,
      });
  return tiles;
}

function tileCanvas(source, tile, maxPixels = 1.2e6) {
  const x = Math.round((source.width * tile.x) / 100), y = Math.round((source.height * tile.y) / 100);
  const w = Math.min(source.width - x, Math.round((source.width * tile.w) / 100));
  const h = Math.min(source.height - y, Math.round((source.height * tile.h) / 100));
  const ratio = Math.min(1, Math.sqrt(maxPixels / (w * h)));
  const canvas = document.createElement('canvas');
  canvas.width = Math.max(1, Math.round(w * ratio));
  canvas.height = Math.max(1, Math.round(h * ratio));
  const ctx = canvas.getContext('2d', { alpha: false });
  ctx.imageSmoothingQuality = 'high';
  ctx.drawImage(source, x, y, w, h, 0, 0, canvas.width, canvas.height);
  return canvas;
}

/**
 * Cut one book's title out of the shelf photo, turned so it reads left to right.
 * The place comes from the server's text detector, in pixels of a photo `photo.width` wide.
 */
function spineCrop(source, place, photo) {
  const values = place && [place.x, place.y, place.length, place.height, place.line, place.angle];
  if (!values || !values.every(Number.isFinite) || !(photo?.width > 0) || place.length < 4 || place.height < 4) return null;
  const k = source.width / photo.width;
  const length = place.length * k, height = place.height * k, line = Math.min(place.line, place.height) * k;
  // Room around the lettering shows the spine it is printed on.
  const w = length + 2 * (line + 0.08 * length), h = height + 1.4 * line;
  const ratio = Math.min(1, 1200 / Math.max(w, h));
  const canvas = document.createElement('canvas');
  canvas.width = Math.max(1, Math.round(w * ratio));
  canvas.height = Math.max(1, Math.round(h * ratio));
  const ctx = canvas.getContext('2d', { alpha: false });
  ctx.fillStyle = '#fff';
  ctx.fillRect(0, 0, canvas.width, canvas.height);
  ctx.imageSmoothingQuality = 'high';
  ctx.translate(canvas.width / 2, canvas.height / 2);
  ctx.scale(ratio, ratio);
  ctx.rotate(-place.angle);
  ctx.drawImage(source, -place.x * k, -place.y * k);
  return { src: canvas.toDataURL('image/jpeg', 0.84), width: canvas.width, height: canvas.height };
}

/**
 * Cut one book's front cover out of a photo of several covers, turned upright.
 * The rectangle comes from the server, in pixels of a photo `photo.width` wide.
 */
function coverCrop(source, cover, photo) {
  const values = cover && [cover.x, cover.y, cover.width, cover.height, cover.angle];
  if (!values || !values.every(Number.isFinite) || !(photo?.width > 0) || cover.width < 8 || cover.height < 8) return null;
  const k = source.width / photo.width, w = cover.width * k, h = cover.height * k;
  const canvas = document.createElement('canvas');
  canvas.width = Math.max(1, Math.round(w));
  canvas.height = Math.max(1, Math.round(h));
  const ctx = canvas.getContext('2d', { alpha: false });
  ctx.fillStyle = '#fff';
  ctx.fillRect(0, 0, canvas.width, canvas.height);
  ctx.imageSmoothingQuality = 'high';
  ctx.translate(canvas.width / 2, canvas.height / 2);
  ctx.rotate(-cover.angle);
  ctx.drawImage(source, -cover.x * k, -cover.y * k);
  return canvas;
}
/** The upright box around a found cover, in whole percentages of the photo, to start the hand crop from. */
export function coverBox(cover, photo) {
  if (!cover || !(photo?.width > 0) || !(photo?.height > 0)) return null;
  const cos = Math.abs(Math.cos(cover.angle)), sin = Math.abs(Math.sin(cover.angle));
  const w = cover.width * cos + cover.height * sin, h = cover.width * sin + cover.height * cos;
  const pct = (value, size) => Math.max(0, Math.min(97, Math.round((value * 100) / size)));
  const left = pct(cover.x - w / 2, photo.width), top = pct(cover.y - h / 2, photo.height);
  return { left, top, right: Math.min(pct(photo.width - cover.x - w / 2, photo.width), 98 - left),
    bottom: Math.min(pct(photo.height - cover.y - h / 2, photo.height), 98 - top) };
}

/** A title's place as fractions of the photo, so the book page can mark it on the kept shelf photo. */
function shelfPlace(place, photo) {
  const values = place && [place.x, place.y, place.length, place.height, place.angle];
  if (!values || !values.every(Number.isFinite) || !(photo?.width > 0) || !(photo?.height > 0)) return null;
  return { x: place.x / photo.width, y: place.y / photo.height, w: place.length / photo.width, h: place.height / photo.height, angle: place.angle };
}

